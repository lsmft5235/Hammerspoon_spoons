--- Returns:
---  * The WallpaperRotator object
function obj:bindHotkeys(mapping)
    local def = {
        rotate = function()
            self:rotate()
            if self.notifyOnChange then
                hs.alert.show("Wallpaper Rotated 🖼️")
            end
        end,
        choose_folder = function()
            self:chooseFolder()
        end,
        set_interval = function()
