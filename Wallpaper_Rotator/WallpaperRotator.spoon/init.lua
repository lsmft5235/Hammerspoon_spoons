-- Helper: ensure staging directory exists
local function ensureStagingDir(dir)
    local attrs = hs.fs.attributes(dir)
    if not attrs then
        local ok, err = hs.fs.mkdir(dir)
        if not ok then return false, err end
    elseif attrs.mode ~= "directory" then
        return false, "Not a directory: " .. tostring(dir)
    end
    return true
end

-- Helper: binary file copy
local function copyFile(src, dst)
    local infile, err = io.open(src, "rb")
    if not infile then return false, err end
    local outfile, outErr = io.open(dst, "wb")
    if not outfile then
        infile:close()
        return false, outErr
    end
    while true do
        local block, readErr = infile:read(65536)
        if readErr then
            infile:close()
            outfile:close()
            return false, readErr
        end
        if not block then break end
        local written, writeErr = outfile:write(block)
        if not written then
            infile:close()
            outfile:close()
            return false, writeErr
        end
    end
    local inputClosed, inputErr = infile:close()
    local outputClosed, outputErr = outfile:close()
    if not inputClosed then return false, inputErr end
    if not outputClosed then return false, outputErr end
    return true
end

-- Helper: percent-decode a file:// URL so encoding differences don't cause false mismatches
local function decodeUrl(url)
    if not url then return url end
    return (url:gsub("%%(%x%x)", function(hex) return string.char(tonumber(hex, 16)) end))
end

-- Fallback for displays (e.g. TV-profile HDMI screens) that reject hs.screen:desktopImageURL()
-- Runs osascript via hs.task (async) instead of hs.osascript.applescript, which blocks Hammerspoon's main thread
local function setWallpaperViaSystemEvents(desktopIndex, filePath, onComplete)
    local escapedPath = filePath:gsub('"', '\\"')
    local script = string.format([[
        tell application "System Events"
            set picture of desktop %d to POSIX file "%s"
        end tell
    ]], desktopIndex, escapedPath)

    local watchdog, finished
    local function finish(ok, err)
        if finished then return end
        finished = true
        if watchdog then watchdog:stop() end
        onComplete(ok, err)
    end
    local task = hs.task.new("/usr/bin/osascript", function(exitCode, _, stdErr)
        finish(exitCode == 0, stdErr)
    end, { "-e", script })

    if not task then
        onComplete(false, "Could not create osascript task")
        return
    end

    -- Guard against a hung osascript/System Events process blocking future rotations
    watchdog = hs.timer.doAfter(8, function()
        obj.logger.w(string.format("System Events fallback for desktop %d timed out after 8s; terminating.", desktopIndex))
        task:terminate()
        finish(false, "System Events timed out after 8s")
    end)

    if not task:start() then finish(false, "Could not start osascript task") end
end

local function reportError(self, msg)
    self.logger.e("WallpaperRotator: " .. msg)
    hs.alert.show("WallpaperRotator: " .. msg)
end

local function isManagedStagingFile(name)
    local stem, ext = name:match("^(.*)%.([^.]+)$")
    if not ext or not obj.allowedExtensions[ext:lower()] then return false end
    if stem == "stage_a" or stem == "stage_b" then return true end
    local uuid = stem:match("^stage_diagnostic_(.+)$") or stem:match("^stage_(.+)$")
    return uuid and uuid:match("^%x%x%x%x%x%x%x%x%-%x%x%x%x%-%x%x%x%x%-%x%x%x%x%-%x%x%x%x%x%x%x%x%x%x%x%x$") ~= nil
end

--- WallpaperRotator:cleanStaging()
--- Method
--- Prunes oldest managed regular files to maxStagedFiles and maxStagedBytes.
--- Protects connected screens' reported wallpapers and in-flight operations.
--- Does not protect inactive Spaces or remove macOS Wallpaper history entries.
function obj:cleanStaging()
    local limits = { self.maxStagedFiles, self.maxStagedBytes }
    for i = 1, 2 do
        local limit = limits[i]
        if type(limit) ~= "number" or limit < 1 or limit == math.huge or limit % 1 ~= 0 then
            reportError(self, "Staging limits must be positive finite integers.")
            return self
        end
    end
    local stagingDir = hs.fs.pathToAbsolute(self.stagingDir)
    local sourceDir = hs.fs.pathToAbsolute(self.dir)
    if not stagingDir or not sourceDir then
        self.logger.w("Skipping staging cleanup: directory paths could not be resolved.")
        return self
    end
    local stagingAttrs = hs.fs.attributes(stagingDir)
    local sourceAttrs = hs.fs.attributes(sourceDir)
    if not stagingAttrs or not sourceAttrs or
        (stagingAttrs.dev == sourceAttrs.dev and stagingAttrs.ino == sourceAttrs.ino) then
        self.logger.w("Skipping staging cleanup: source and staging directories are ambiguous or identical.")
        return self
    end
    local protected = {}
    for path in pairs(self.inFlightPaths) do
        local absolute = hs.fs.pathToAbsolute(path)
        if not absolute then
            self.logger.w("Skipping staging cleanup: an in-flight path could not be resolved.")
            return self
        end
        protected[absolute] = true
    end
    local screensOk, screens = pcall(hs.screen.allScreens)
    if not screensOk or not screens or #screens == 0 then
        self.logger.w("Skipping staging cleanup: no screen references available.")
        return self
    end
    for _, screen in ipairs(screens) do
        local ok, url = pcall(screen.desktopImageURL, screen)
        if not ok or type(url) ~= "string" or url == "" then
            self.logger.w("Skipping staging cleanup: could not read a screen wallpaper URL.")
            return self
        end
        if url:sub(1, 7) == "file://" then
            local path = decodeUrl(url:sub(8):gsub("^localhost/", "/"))
            local absolute = hs.fs.pathToAbsolute(path)
            if not absolute then
                self.logger.w("Skipping staging cleanup: a screen wallpaper path could not be resolved.")
                return self
            end
            protected[absolute] = true
        else
            self.logger.w("Skipping staging cleanup: unrecognized screen wallpaper URL.")
            return self
        end
    end
    local entries, count, bytes = {}, 0, 0
    local ok, err = pcall(function()
        for name in hs.fs.dir(stagingDir) do
            if isManagedStagingFile(name) then
                local path = stagingDir .. "/" .. name
                local attrs, attrErr = hs.fs.symlinkAttributes(path)
                if not attrs then error(attrErr or ("Cannot inspect " .. path)) end
                if attrs.mode == "file" then
                    if type(attrs.size) ~= "number" or type(attrs.modification) ~= "number" then
                        error("Missing staging size or modification time: " .. path)
                    end
                    entries[#entries + 1] = { path = path, size = attrs.size, time = attrs.modification }
                    count, bytes = count + 1, bytes + attrs.size
                end
            end
        end
    end)
    if not ok then
        self.logger.w("Skipping staging cleanup: " .. tostring(err))
        return self
    end
    table.sort(entries, function(a, b)
        if a.time == b.time then return a.path < b.path end
        return a.time < b.time
    end)
    local removed = 0
    for _, entry in ipairs(entries) do
        if count <= self.maxStagedFiles and bytes <= self.maxStagedBytes then break end
        if not protected[entry.path] then
            local deleted, deleteErr = os.remove(entry.path)
            if deleted then
                count, bytes, removed = count - 1, bytes - entry.size, removed + 1
            else
                self.logger.w("Could not remove staging file " .. entry.path .. ": " .. tostring(deleteErr))
            end
        end
    end
    self.logger.i(string.format("Staging cleanup: removed %d; retained %d files / %d bytes.", removed, count, bytes))
    if count > self.maxStagedFiles or bytes > self.maxStagedBytes then
        self.logger.w("Staging retention targets unmet: protected files or deletion failures prevent further pruning.")
    end
    return self
end

-- Helper: Retrieve valid image files from directory
-- Returns files, errorMessage (errorMessage is nil on success)
local function getWallpaperFiles(dir)
    local files = {}
    local attrs = hs.fs.attributes(dir)
    if not attrs or attrs.mode ~= "directory" then
        return files, "Directory does not exist or is not accessible: " .. tostring(dir)
    end

    local ok, iterFn, dirObj = pcall(hs.fs.dir, dir)
    if not ok or not iterFn then
        return files, "Could not list directory (check Hammerspoon's Files & Folders permission): " .. tostring(iterFn)
    end

    for file in iterFn, dirObj do
        if file ~= "." and file ~= ".." then
            local ext = file:match("^.+(%..+)$")
            if ext then
                ext = ext:sub(2):lower()
                if obj.allowedExtensions[ext] then
                    table.insert(files, dir .. "/" .. file)
                end
            end
        end
    end
    return files
end

-- Applies a staged wallpaper to every screen, falling back to System Events when needed.
function obj:applyWallpaperDirect(stagedPath, fileUrl, onComplete)
    local failedScreens = {}
    local screensOk, screens = pcall(hs.screen.allScreens)
    if not screensOk or not screens then
        reportError(self, "Could not enumerate screens: " .. tostring(screens))
        if onComplete then onComplete(false) end
        return
    end
    local pendingChecks = #screens
    local pendingFallbacks = 0
    local completed = false

    local function maybeReportFailures()
        if not completed and pendingChecks == 0 and pendingFallbacks == 0 then
            completed = true
            if #failedScreens > 0 then
                local msg = "macOS rejected the image for: " .. table.concat(failedScreens, ", ") ..
                    "\nCheck Hammerspoon Automation access to System Events in System Settings."
                reportError(self, msg)
            end
            if onComplete then onComplete(#failedScreens == 0 and #screens > 0) end
        end
    end

    if #screens == 0 then
        reportError(self, "No connected screens available to apply wallpaper.")
        maybeReportFailures()
        return
    end
    for index, screen in ipairs(screens) do
        local setOk, setErr = pcall(screen.desktopImageURL, screen, fileUrl)
        if not setOk then self.logger.w("Wallpaper URL request failed: " .. tostring(setErr)) end
        local screenLabel = screen:name() or tostring(screen:id())

        -- Delay the readback: macOS doesn't always reflect the new URL in the same tick,
        -- and comparing immediately caused false-positive fallback triggers
        hs.timer.doAfter(0.25, function()
            pendingChecks = pendingChecks - 1
            local readOk, actualUrl = pcall(screen.desktopImageURL, screen)
            if not readOk then self.logger.w("Wallpaper URL readback failed: " .. tostring(actualUrl)) end
            if not setOk or not readOk or decodeUrl(actualUrl) ~= decodeUrl(fileUrl) then
                -- Some displays (e.g. TV-profile HDMI screens) reject the NSScreen API; retry via System Events
                pendingFallbacks = pendingFallbacks + 1
                self.logger.i("Fallback: invoking System Events for screen " .. screenLabel)
                setWallpaperViaSystemEvents(index, stagedPath, function(ok, errText)
                    pendingFallbacks = pendingFallbacks - 1
                    if ok then
                        self.logger.i("Fallback succeeded for screen " .. screenLabel)
                    else
                        self.logger.e("Fallback failed for screen " .. screenLabel .. ": " .. tostring(errText))
                        table.insert(failedScreens, screenLabel)
                    end
                    maybeReportFailures()
                end)
            end
            maybeReportFailures()
        end)
    end
end

--- WallpaperRotator:rotate()
--- Method
--- Selects and applies a random wallpaper image to all connected screens.
--- Uses a fresh UUID staging path each time to avoid stale path-based renders.
--- Supports smooth hardware-accelerated crossfade transitions via hs.canvas.
--- Prompts to select a folder if no valid images are found.
---
--- Returns:
---  * The WallpaperRotator object
function obj:rotate()
    if self.isTransitioning or self.cacheCleanupTask then
        self.logger.d("Transition or cache cleanup in progress, skipping rotation.")
        return self
    end

    local wallpapers, err = getWallpaperFiles(self.dir)

    if err then
        self.logger.e(err)
        hs.alert.show("WallpaperRotator: " .. err)
        return self
    end

    if #wallpapers == 0 then
        self.logger.w("No valid images found in " .. tostring(self.dir))
        hs.alert.show("WallpaperRotator: No valid images found in " .. tostring(self.dir) .. "\nPlease select a folder.")
        self:chooseFolder()
        return self
    end

    local stagingOk, stagingErr = ensureStagingDir(self.stagingDir)
    if not stagingOk then
        reportError(self, "Could not create staging directory: " .. tostring(stagingErr))
        return self
    end

    math.randomseed(os.time())
    local randomIndex = math.random(1, #wallpapers)
    local selected = wallpapers[randomIndex]

    local ext = selected:match("^.+(%..+)$") or ".jpg"
    local stagingName = "stage_" .. hs.host.uuid() .. ext
    local stagedPath = self.stagingDir .. "/" .. stagingName

    local copyOk, copyErr = copyFile(selected, stagedPath)
    if not copyOk then
        local msg = "WallpaperRotator: Failed to stage wallpaper file: " .. tostring(copyErr)
        self.logger.e(msg)
        hs.alert.show(msg)
        if hs.fs.attributes(stagedPath) then
            local removed, removeErr = os.remove(stagedPath)
            if not removed then self.logger.w("Could not remove partial staging file: " .. tostring(removeErr)) end
        end
        return self
    end

    local fileUrl = "file://" .. stagedPath:gsub("([^%w%-%._~/])", function(c)
        return string.format("%%%02X", string.byte(c))
    end)
    self.logger.i(string.format("Staged wallpaper [unique path]: %s -> %s", selected, stagedPath))
    self.inFlightPaths[stagedPath] = true
    self:cleanStaging()

    self.rotationCount = (self.rotationCount or 0) + 1
    if self.enableCacheCleanup then
        if type(self.cleanupInterval) ~= "number" or self.cleanupInterval < 1 or
            self.cleanupInterval == math.huge or self.cleanupInterval % 1 ~= 0 then
            reportError(self, "cleanupInterval must be a positive finite integer.")
        elseif self.rotationCount % self.cleanupInterval == 0 then
            self.cacheCleanupPending = true
        end
    end
    local applicationDone, overlayDone, finished = false, false, false
    local function finishRotation()
        if finished or not applicationDone or not overlayDone then return end
        finished = true
        self.inFlightPaths[stagedPath] = nil
        self:cleanStaging()
        if self.cacheCleanupPending and not next(self.inFlightPaths) then self:cleanCache() end
    end
    local function applicationComplete()
        applicationDone = true
        finishRotation()
    end

    -- Reset countdown timer to full interval
    self.remainingSeconds = self.interval
    self:updateCountdown()

    -- Check if smooth fade transition is enabled and image is readable
    local img = self.enableFadeTransition and hs.image.imageFromPath(stagedPath)
    if not img then
        overlayDone = true
        self:applyWallpaperDirect(stagedPath, fileUrl, applicationComplete)
        return self
    end

    -- Smooth Crossfade Overlay via hs.canvas
    self.isTransitioning = true
    self.rotationToken = (self.rotationToken or 0) + 1
    local rotationToken = self.rotationToken
    local fadeDuration = self.fadeDuration or 1.2
    local transitionCanvases = {}
    local function deleteOverlays()
        if overlayDone then return end
        for _, canvas in ipairs(transitionCanvases) do canvas:delete() end
        overlayDone = true
        if self.rotationToken == rotationToken then self.isTransitioning = false end
        finishRotation()
    end

    for _, screen in ipairs(hs.screen.allScreens()) do
        local screenFrame = screen:fullFrame()
        local canvas = hs.canvas.new(screenFrame)
        canvas:level(hs.canvas.windowLevels.desktop)
        canvas:behaviorAsLabels({ "canJoinAllSpaces", "stationary", "ignoresCycle" })
        canvas:clickActivating(false)
        canvas:appendElements({
            type = "image",
            image = img,
            imageScaling = "scaleToFit",
            frame = { x = 0, y = 0, w = screenFrame.w, h = screenFrame.h }
        })
        canvas:show(fadeDuration)
        table.insert(transitionCanvases, canvas)
    end

    -- Once the overlay reaches 100% opacity, swap the macOS wallpaper behind it
    hs.timer.doAfter(fadeDuration, function()
        self:applyWallpaperDirect(stagedPath, fileUrl, function()
            applicationComplete()
            -- Hold the overlay briefly after all URL checks/fallback tasks settle.
            hs.timer.doAfter(0.6, deleteOverlays)
        end)
    end)

    -- Safety net: force cleanup if this rotation's transition never completes normally
    hs.timer.doAfter(fadeDuration + 6, function()
        if self.isTransitioning and self.rotationToken == rotationToken then
            self.logger.w("Rotation watchdog: transition stuck, forcing cleanup.")
            deleteOverlays()
        end
    end)

    return self
end

--- WallpaperRotator:cleanCache()
--- Method
--- Asynchronously purges BMPs in the existing macOS wallpaper cache locations.
--- This includes potentially active caches. Defers until in-flight rotations settle.
--- Completion and measured results are logged; overlapping requests are coalesced.
---
--- Returns:
---  * The WallpaperRotator object
function obj:cleanCache()
    if self.cacheCleanupTask then
        self.logger.i("Wallpaper cache cleanup already running; request coalesced.")
        return self
    end
    if next(self.inFlightPaths) then
        self.cacheCleanupPending = true
        self.logger.i("Wallpaper cache cleanup deferred until wallpaper operations settle.")
        return self
    end
    self.cacheCleanupPending = false
    local userHome = os.getenv("HOME")
    local containerCacheDir = userHome .. "/Library/Containers/com.apple.wallpaper.agent/Data/Library/Caches/com.apple.wallpaper.caches"
    local watchdog, finished, timedOut
    local function finish(exitCode, stdOut, stdErr)
        if finished then return end
        finished = true
        if watchdog then watchdog:stop() end
        self.cacheCleanupTask = nil
        if stdOut and stdOut ~= "" then self.logger.i("Wallpaper cache measurements:\n" .. stdOut) end
        if timedOut then
            reportError(self, "Wallpaper cache cleanup timed out; final task exit: " .. tostring(exitCode) ..
                ". " .. tostring(stdErr))
        elseif exitCode == 0 then
            self.logger.i("Wallpaper cache cleanup completed successfully.")
        else
            reportError(self, "Wallpaper cache cleanup failed (" .. tostring(exitCode) .. "): " .. tostring(stdErr))
        end
    end
    local task = hs.task.new("/bin/sh", finish, { cacheCleanupScript, containerCacheDir })
    if not task then
        finish(-1, "", "Could not create cache cleanup task")
        return self
    end
    self.cacheCleanupTask = task
    watchdog = hs.timer.doAfter(30, function()
        timedOut = true
        reportError(self, "Cache cleanup exceeded 30s; requesting termination. Rotations remain paused until it exits.")
        task:terminate()
    end)
    if not task:start() then finish(-1, "", "Could not start cache cleanup task") end

    return self
end

-- Builds and positions the countdown overlay on the primary screen.
function obj:createCountdownCanvas()
    if self.countdownCanvas then
        self.countdownCanvas:delete()
        self.countdownCanvas = nil
    end

    if not self.showCountdown then return self end

    local screen = hs.screen.primaryScreen() or hs.screen.mainScreen()
    if not screen then return self end

    local screenFrame = screen:fullFrame()
    local badgeW = 76
    local badgeH = 26
    local posX = screenFrame.x + 18
    local posY = screenFrame.y + screenFrame.h - badgeH - 18

    self.countdownCanvas = hs.canvas.new({
        x = posX,
        y = posY,
        w = badgeW,
        h = badgeH
    })

    self.countdownCanvas:level(hs.canvas.windowLevels.overlay)
    self.countdownCanvas:behaviorAsLabels({ "canJoinAllSpaces", "stationary" })
    self.countdownCanvas:clickActivating(false)

    self.countdownCanvas:appendElements(
        -- Element 1: Rounded translucent background pill
        {
            type = "rectangle",
            action = "fill",
            fillColor = { red = 0.1, green = 0.1, blue = 0.1, alpha = 0.65 },
            roundedRectRadii = { xRadius = 6, yRadius = 6 },
            frame = { x = 0, y = 0, w = badgeW, h = badgeH }
        },
        -- Element 2: Centered countdown text
        {
            type = "text",
            text = "0:00",
            textFont = "Menlo-Bold",
            textSize = 12,
            textColor = { white = 0.95, alpha = 0.9 },
            textAlignment = "center",
            frame = { x = 0, y = 4, w = badgeW, h = badgeH - 4 }
        }
    )

    self.countdownCanvas:show()
    return self
end

-- Updates the countdown text element on the canvas.
function obj:updateCountdown()
    if not self.countdownCanvas or not self.showCountdown then return self end

    local totalSecs = math.max(0, math.floor(self.remainingSeconds or 0))
    local mins = math.floor(totalSecs / 60)
    local secs = totalSecs % 60
    local textStr = string.format("%d:%02d", mins, secs)

    self.countdownCanvas[2].text = textStr
    return self
end

-- Initializes and starts the one-second countdown ticker.
function obj:startCountdown()
    self:stopCountdown()
    if not self.showCountdown then return self end

    self:createCountdownCanvas()
    self.remainingSeconds = self.interval
    self:updateCountdown()

    self.countdownTimer = hs.timer.doEvery(1, function()
        if self.remainingSeconds and self.remainingSeconds > 0 then
            self.remainingSeconds = self.remainingSeconds - 1
        end
        self:updateCountdown()
    end)

    return self
end

-- Stops the countdown timer and deletes the overlay canvas.
function obj:stopCountdown()
    if self.countdownTimer then
        self.countdownTimer:stop()
        self.countdownTimer = nil
    end
    if self.countdownCanvas then
        self.countdownCanvas:delete()
        self.countdownCanvas = nil
    end
    return self
end

--- WallpaperRotator:chooseFolder()
--- Method
--- Opens a macOS directory selection dialog to pick a new wallpaper directory.
--- Persists the selected path across restarts.
---
--- Returns:
---  * The WallpaperRotator object
function obj:chooseFolder()
    hs.focus()

    -- Ensure defaultPath exists and is a directory
    local defaultPath = self.dir
    local attrs = defaultPath and hs.fs.attributes(defaultPath)
    if not attrs or attrs.mode ~= "directory" then
        defaultPath = os.getenv("HOME")
    end

    local selection = hs.dialog.chooseFileOrFolder(
        "Choose a wallpaper folder",
        defaultPath,
        false, -- canChooseFiles
        true,  -- canChooseDirectories
        false  -- allowsMultipleSelection
    )

    -- Grab the first entry regardless of whether the returned table uses a
    -- numeric or string "1" key (observed to vary across Hammerspoon versions)
    local chosenPath = nil
    if type(selection) == "table" then
        chosenPath = selection[1] or selection["1"]
    end

    if chosenPath then
        -- Normalize trailing slash
        chosenPath = chosenPath:gsub("/$", "")
        self:setDirectory(chosenPath)
        hs.alert.show("Wallpaper folder updated:\n" .. self.dir)
        self:rotate()
    end

    return self
end

